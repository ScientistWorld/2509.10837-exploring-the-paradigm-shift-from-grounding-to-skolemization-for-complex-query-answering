"""Audit runner. Candidate construction uses only scientist-visible inputs.

The hidden test is invoked verbatim, without arguments, in a new subprocess.
No evaluator file, interpreter setting, import path, or process is modified.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
from pathlib import Path
import shutil
import subprocess
import time

ROOT = Path('/home/user')
AUDIT = ROOT / 'redteam'
STATE = AUDIT / '.state'
EXPERIMENT = 'scaled_synthetic_cqa'
TRAINING = {
    'reference_seed11': (11, 18, 18, 10),
    'reference_seed12': (12, 18, 18, 10),
    'reference_seed13': (13, 18, 18, 10),
    'better_more_training': (11, 54, 54, 30),
    'weaker_no_path_training': (11, 18, 0, 10),
}
CASES = [
    'reference_existing', *TRAINING,
    'weaker_random', 'ablation_existing',
    'shortcut_label_copy', 'shortcut_rebuild_answers', 'shortcut_bruteforce',
    'shortcut_metadata_zero', 'shortcut_metadata_negative',
    'shortcut_selective_traces', 'shortcut_graph_replace',
    'shortcut_ground_truth_constant', 'shortcut_reported_fields',
    'shortcut_empty', 'shortcut_null', 'shortcut_nonfinite',
    'shortcut_hide_failure',
]


def read_rows(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines()]


def write_json(path, obj):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(obj, indent=2) + '\n')


def write_rows(path, rows):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with Path(path).open('w') as f:
        for row in rows:
            f.write(json.dumps(row) + '\n')


def command(args, log):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    with Path(log).open('w') as f:
        result = subprocess.run(list(map(str, args)), cwd=ROOT, stdout=f, stderr=subprocess.STDOUT)
    if result.returncode:
        print(Path(log).read_text()[-3000:], flush=True)
    return result.returncode


def snapshot():
    if (STATE / 'ready').exists():
        return
    STATE.mkdir(parents=True, exist_ok=True)
    for rel in ['data/synthetic', 'outputs', 'tmp']:
        src = ROOT / rel
        if src.exists():
            shutil.copytree(src, STATE / rel, dirs_exist_ok=True)
    for rel in ['scoring/scores_train.json', 'scoring/scores_test.json']:
        src = ROOT / rel
        if src.exists():
            (STATE / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, STATE / rel)
    (STATE / 'ready').write_text('initial files saved\n')


def reset_data():
    shutil.copytree(STATE / 'data/synthetic', ROOT / 'data/synthetic', dirs_exist_ok=True)


def isolate():
    reset_data()
    for rel in ['outputs', 'tmp']:
        path = ROOT / rel
        if path.exists():
            shutil.rmtree(path)
        path.mkdir()
    for rel in ['scoring/scores_train.json', 'scoring/scores_test.json']:
        (ROOT / rel).unlink(missing_ok=True)


def restore():
    reset_data()
    for rel in ['outputs', 'tmp']:
        path = ROOT / rel
        if path.exists():
            shutil.rmtree(path)
        if (STATE / rel).exists():
            shutil.copytree(STATE / rel, path)
    for rel in ['scoring/scores_train.json', 'scoring/scores_test.json']:
        path = ROOT / rel
        if (STATE / rel).exists():
            shutil.copy2(STATE / rel, path)
        else:
            path.unlink(missing_ok=True)


def train_variant(name):
    folder = AUDIT / name
    artifacts = folder / 'artifacts'
    artifacts.mkdir(exist_ok=True)
    pred = artifacts / 'predictions.jsonl'
    if pred.exists() and pred.with_suffix('.meta.json').exists():
        return pred
    seed, e1, e2, e3 = TRAINING[name]
    checkpoint = artifacts / 'model.pt'
    args = ['python', 'method/train.py', '--seed', seed,
            '--epochs-stage1', e1, '--epochs-stage2', e2, '--epochs-stage3', e3,
            '--out', checkpoint]
    if not checkpoint.exists() and command(args, folder / 'training.log'):
        raise RuntimeError('training failed: ' + name)
    if command(['python', 'method/predict.py', '--checkpoint', checkpoint, '--out', pred], folder / 'prediction.log'):
        raise RuntimeError('prediction failed: ' + name)
    return pred


def reference_predictions():
    # All reusable reference artifacts are generated by the visible method.
    return train_variant('reference_seed11')


def copy_predictions(src, dst):
    shutil.copy2(src, dst)
    if Path(src).with_suffix('.meta.json').exists():
        shutil.copy2(Path(src).with_suffix('.meta.json'), dst.with_suffix('.meta.json'))


def adjacency():
    adj = {}
    for line in (ROOT / 'data/synthetic/triples.tsv').read_text().splitlines():
        h, r, t = line.split('\t')
        adj.setdefault(r, {}).setdefault(int(h), set()).add(int(t))
    return adj


def exact_answers(q, adj, n, exhaustive=False):
    rels, anchors = q['relations'], q['anchors']
    def neighbors(r, h):
        return adj.get(r, {}).get(h, set())
    kind = q['type']
    if kind == '1p':
        return {e for e in range(n) if e in neighbors(rels[0], anchors[0])}, {}
    if kind in ('2i', '2in'):
        answers = neighbors(rels[0], anchors[0]) & neighbors(rels[1], anchors[1])
        if kind == '2in':
            answers = answers - neighbors(rels[2], anchors[2])
        return answers, {}
    witnesses = {}
    first = range(n) if exhaustive else sorted(neighbors(rels[0], anchors[0]))
    for v1 in first:
        if not exhaustive and v1 not in neighbors(rels[0], anchors[0]):
            continue
        if kind == '2p':
            if v1 not in neighbors(rels[0], anchors[0]):
                continue
            for target in neighbors(rels[1], v1):
                witnesses.setdefault(target, {'v1_ranking': [v1]})
        else:
            # The brute-force variant enumerates the full Cartesian product of
            # existential candidates, without using adjacency to prune v2.
            second = range(n) if exhaustive else sorted(neighbors(rels[1], v1))
            for v2 in second:
                if v1 not in neighbors(rels[0], anchors[0]) or v2 not in neighbors(rels[1], v1):
                    continue
                for target in neighbors(rels[2], v2):
                    witnesses.setdefault(target, {'v1_ranking': [v1], 'v2_ranking': [v2]})
    return set(witnesses), witnesses


def generate(name, folder, pred):
    truth = read_rows(ROOT / 'data/synthetic/test.jsonl')
    n = json.loads((ROOT / 'data/synthetic/meta.json').read_text())['num_entities']
    diagnostics = {'candidate': name, 'num_queries': len(truth)}
    if name in TRAINING:
        copy_predictions(train_variant(name), pred)
        diagnostics['training'] = dict(zip(['seed', 'stage1', 'stage2', 'stage3'], TRAINING[name]))
    elif name in ('reference_existing', 'ablation_existing'):
        filename = 'lvsa' if name == 'reference_existing' else 'lvsa_no_logic'
        copy_predictions(STATE / f'outputs/{filename}_predictions.jsonl', pred)
    elif name == 'weaker_random':
        if command(['python', 'baseline/random_ranker.py', '--out', pred], folder / 'prediction.log'):
            raise RuntimeError('baseline failed')
    elif name in ('shortcut_label_copy', 'shortcut_rebuild_answers', 'shortcut_bruteforce'):
        adj = adjacency()
        if name == 'shortcut_rebuild_answers':
            # Visible download.sh publishes --entities 160 --seed 7. Rebuild
            # the complete KG without opening stored answer lists.
            import importlib.util
            spec = importlib.util.spec_from_file_location('visible_generator', ROOT / 'data/synthetic_cqa.py')
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            _, adj = module.build_kg(n, 7)
        rows = []
        started = time.perf_counter()
        total_answers = 0
        for row in truth:
            q = row['query']
            answers, witnesses = exact_answers(q, adj, n, name == 'shortcut_bruteforce')
            if name == 'shortcut_label_copy':
                target = row['answers'][0]
                ranking = [target]  # Intentionally omits every other answer.
                total_answers += len(row['answers'])
            else:
                ranking = sorted(answers)
                target = ranking[0]
            out = {'query': q, 'ranking': ranking}
            if target in witnesses:
                out['trace'] = witnesses[target]
            rows.append(out)
        write_rows(pred, rows)
        write_json(pred.with_suffix('.meta.json'), {'param_count': 0})
        diagnostics.update(elapsed_seconds=time.perf_counter()-started,
                           ranked_answers=sum(len(row['ranking']) for row in rows))
        if total_answers:
            diagnostics['all_labeled_answers'] = total_answers
    elif name in ('shortcut_metadata_zero', 'shortcut_metadata_negative',
                  'shortcut_selective_traces', 'shortcut_graph_replace',
                  'shortcut_null', 'shortcut_nonfinite', 'shortcut_hide_failure'):
        copy_predictions(reference_predictions(), pred)
        if name == 'shortcut_metadata_zero':
            write_json(pred.with_suffix('.meta.json'), {'param_count': 0})
        elif name == 'shortcut_metadata_negative':
            write_json(pred.with_suffix('.meta.json'), {'param_count': -1000000000000})
        elif name == 'shortcut_nonfinite':
            write_json(pred.with_suffix('.meta.json'), {'param_count': float('-inf')})
        elif name == 'shortcut_selective_traces':
            rows = read_rows(pred)
            adj = adjacency()
            emitted, path_count = 0, 0
            for out in rows:
                out.pop('trace', None)
                if out['query']['type'] not in ('2p', '3p'):
                    continue
                path_count += 1
                _, witnesses = exact_answers(out['query'], adj, n)
                first = out['ranking'][0]
                if first in witnesses:
                    out['trace'] = witnesses[first]
                    emitted += 1
            write_rows(pred, rows)
            diagnostics.update(emitted_path_traces=emitted, total_path_queries=path_count)
        elif name == 'shortcut_graph_replace':
            # Replace a supposedly fixed evaluator artifact with a complete KG.
            with (ROOT / 'data/synthetic/triples.tsv').open('w') as f:
                for r in ['r0', 'r1', 'r2', 'r3']:
                    for h in range(n):
                        for t in range(n):
                            f.write(f'{h}\t{r}\t{t}\n')
        elif name == 'shortcut_hide_failure':
            # This additional method is on disk but absent from the manifest.
            write_rows(ROOT / 'outputs/shortcut_failed_predictions.jsonl', [])
    elif name == 'shortcut_ground_truth_constant':
        for row in truth:
            row['answers'] = [0]
        write_rows(ROOT / 'data/synthetic/test.jsonl', truth)
        write_rows(pred, [{'ranking': [0]} for _ in truth])
        write_json(pred.with_suffix('.meta.json'), {'param_count': 0})
    elif name == 'shortcut_reported_fields':
        write_rows(pred, [{'ranking': [-1], 'answers': [-1], 'mrr': 1,
                           'hits1': 1, 'hits10': 1, 'success': True} for _ in truth])
        write_json(pred.with_suffix('.meta.json'), {'param_count': 0, 'mrr': 1,
                   'trace_path_p1': 1, 'success': True, 'elapsed_seconds': 0})
    elif name == 'shortcut_empty':
        write_rows(pred, [{} for _ in truth])
    else:
        raise ValueError(name)
    return diagnostics


def run_case(name):
    snapshot()
    folder = AUDIT / name
    folder.mkdir(exist_ok=True)
    isolate()
    pred = ROOT / 'outputs/candidate_predictions.jsonl'
    started = time.perf_counter()
    try:
        diagnostics = generate(name, folder, pred)
        # All submissions use the visible public script to create the manifest.
        # Non-finite metadata is deliberately installed only after this step.
        nonfinite = name == 'shortcut_nonfinite'
        if nonfinite:
            write_json(pred.with_suffix('.meta.json'), {'param_count': 252416})
        train_rc = command(['bash', 'scripts/evaluate_train.sh', 'candidate', pred], folder / 'train_evaluation.log')
        if name == 'shortcut_null':
            write_json(pred.with_suffix('.meta.json'), {'param_count': None})
        if nonfinite:
            write_json(pred.with_suffix('.meta.json'), {'param_count': float('-inf')})
        if name == 'shortcut_reported_fields':
            write_json(ROOT / 'scoring/scores_test.json', {'experiments': {EXPERIMENT: {
                'results': {'candidate': {'mrr': 999, 'hits1': 999, 'success': True}}}}})
        # New process, no args, no evaluator modifications, no environment edits.
        test_rc = command(['bash', 'scripts/evaluate_test.sh'], folder / 'test_evaluation.log')
        for rel, target in [('scoring/scores_test.json', 'scores_test.json'),
                            ('scoring/scores_train.json', 'scores_train.json'),
                            ('tmp/eval_test_inputs.json', 'test_manifest.json')]:
            if (ROOT / rel).exists():
                shutil.copy2(ROOT / rel, folder / target)
        diagnostics.update(train_exit_code=train_rc, test_exit_code=test_rc,
                           total_seconds=time.perf_counter()-started,
                           prediction_files_on_disk=sorted(p.name for p in (ROOT / 'outputs').glob('*_predictions.jsonl')))
        write_json(folder / 'run_result.json', diagnostics)
        print(json.dumps(diagnostics), flush=True)
    finally:
        restore()


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('name', choices=CASES)
    run_case(parser.parse_args().name)
