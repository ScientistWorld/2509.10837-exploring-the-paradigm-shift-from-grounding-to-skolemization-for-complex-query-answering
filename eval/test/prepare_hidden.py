"""Build the hidden test truth from the official FB15k-237 release zip.

Writes only into ``eval/test/data/`` (gitignored, regenerated by
``scripts/download.sh``):
  * ``test_std_truth.npz`` / ``test_hplus_truth.npz``: the fixed evaluation
    sample of test queries, their non-trivial ("hard") answers and the set of
    entities removed from ranking (benchmark easy answers plus every answer
    already reachable on the observed train+valid graph),
  * ``graph_full.npy``: train+valid+test triples, used to verify intermediate
    witnesses.

The query sample is drawn with the same deterministic procedure as the public
test inputs; when the public files exist the two are checked for equality.
Pure standard library; release pickles go through a restricted unpickler.
"""

from __future__ import annotations

import argparse
import array
import hashlib
import io
import json
import pickle
import random
import struct
import sys
import zipfile
from collections import defaultdict
from pathlib import Path

ROOT = "iscqa-compl-benchmarks/"
STD = ROOT + "old_benchmarks/FB15k-237-betae/"
HPLUS = ROOT + "new_benchmarks/FB15k-237+H/"
NUM_ENTITIES = 14505
STRUCTURES = {
    "1p": ("e", ("r",)),
    "2p": ("e", ("r", "r")),
    "3p": ("e", ("r", "r", "r")),
    "2i": (("e", ("r",)), ("e", ("r",))),
    "3i": (("e", ("r",)), ("e", ("r",)), ("e", ("r",))),
    "ip": ((("e", ("r",)), ("e", ("r",))), ("r",)),
    "pi": (("e", ("r", "r")), ("e", ("r",))),
    "2u": (("e", ("r",)), ("e", ("r",)), ("u",)),
    "up": ((("e", ("r",)), ("e", ("r",)), ("u",)), ("r",)),
    "2in": (("e", ("r",)), ("e", ("r", "n"))),
    "3in": (("e", ("r",)), ("e", ("r",)), ("e", ("r", "n"))),
    "inp": ((("e", ("r",)), ("e", ("r", "n"))), ("r",)),
    "pin": (("e", ("r", "r")), ("e", ("r", "n"))),
    "pni": (("e", ("r", "r", "n")), ("e", ("r",))),
    "4p": ("e", ("r", "r", "r", "r")),
    "4i": (("e", ("r",)), ("e", ("r",)), ("e", ("r",)), ("e", ("r",))),
}
STD_TYPES = ["1p", "2p", "3p", "2i", "3i", "ip", "pi", "2u", "up", "2in", "3in", "inp", "pin", "pni"]
HPLUS_TYPES = STD_TYPES + ["4p", "4i"]
CAP = {"std": 2000, "hplus": 1000}


class SafeUnpickler(pickle.Unpickler):
    ALLOWED = {("builtins", "set"), ("builtins", "frozenset"), ("collections", "defaultdict")}

    def find_class(self, module, name):
        if (module, name) in self.ALLOWED:
            return getattr(__import__(module), name)
        raise pickle.UnpicklingError(f"refusing to load global {module}.{name}")


def load_pickle(zf, member):
    with zf.open(member) as f:
        return SafeUnpickler(io.BufferedReader(f)).load()


def npy_bytes(arr: array.array, shape: tuple) -> bytes:
    if sys.byteorder != "little":
        raise RuntimeError("little-endian host required")
    descr = {"i": "<i4", "h": "<i2"}[arr.typecode]
    header = "{'descr': '%s', 'fortran_order': False, 'shape': %s, }" % (descr, repr(tuple(shape)))
    pad = 64 - ((10 + len(header) + 1) % 64)
    header = header + " " * pad + "\n"
    return b"\x93NUMPY\x01\x00" + struct.pack("<H", len(header)) + header.encode("latin1") + arr.tobytes()


def write_npz(path: Path, arrays: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=1) as z:
        for key, (arr, shape) in arrays.items():
            z.writestr(key + ".npy", npy_bytes(arr, shape))
    tmp.replace(path)


def read_npz_q(path: Path, key: str) -> list:
    """Minimal reader for the int32 query arrays of the public test file."""
    import ast

    with zipfile.ZipFile(path) as z:
        raw = z.read(key + ".npy")
    hlen = struct.unpack("<H", raw[8:10])[0]
    header = ast.literal_eval(raw[10 : 10 + hlen].decode("latin1"))
    if header["descr"] != "<i4":
        raise ValueError("unexpected dtype in public test file")
    arr = array.array("i")
    arr.frombytes(raw[10 + hlen :])
    return list(arr)


def flatten(structure, query, anchors, rels):
    if structure == "e":
        anchors.append(int(query))
    elif structure == "r":
        rels.append(int(query))
    elif structure in ("n", "u"):
        return
    else:
        for s, q in zip(structure, query):
            flatten(s, q, anchors, rels)


def query_row(structure, query):
    anchors, rels = [], []
    flatten(structure, query, anchors, rels)
    return anchors + rels


def is_chain(structure):
    return isinstance(structure, tuple) and len(structure) >= 1 and all(isinstance(x, str) for x in structure) and structure[0] in ("r", "n")


def execute(structure, query, adj, all_entities):
    if structure[0] == "e":
        current = {int(query[0])}
        for s, r in zip(structure[1], query[1]):
            if s == "r":
                nxt = set()
                for e in current:
                    nxt |= adj.get((e, r), set())
                current = nxt
            elif s == "n":
                current = all_entities - current
        return current
    if len(structure) == 2 and is_chain(structure[1]):
        current = execute(structure[0], query[0], adj, all_entities)
        for s, r in zip(structure[1], query[1]):
            if s == "r":
                nxt = set()
                for e in current:
                    nxt |= adj.get((e, r), set())
                current = nxt
            elif s == "n":
                current = all_entities - current
        return current
    if structure[-1] == ("u",):
        out = set()
        for s, q in zip(structure[:-1], query[:-1]):
            out |= execute(s, q, adj, all_entities)
        return out
    parts = [execute(s, q, adj, all_entities) for s, q in zip(structure, query)]
    out = parts[0]
    for p in parts[1:]:
        out = out & p
    return out


def sample_queries(queries, bench, split, qtype, cap):
    ordered = sorted(queries)
    rng = random.Random(f"lvsa-gym|{bench}|{split}|{qtype}|v1")
    chosen = ordered if len(ordered) <= cap else rng.sample(ordered, cap)
    return sorted(chosen)


def csr(rows):
    indptr = array.array("i", [0])
    indices = array.array("i")
    for row in rows:
        indices.extend(sorted(int(x) for x in row))
        indptr.append(len(indices))
    return (indptr, (len(indptr),)), (indices, (len(indices),))


def read_triples(zf, member):
    out = []
    for line in zf.read(member).decode().splitlines():
        if line.strip():
            h, r, t = line.split()
            out.append((int(h), int(r), int(t)))
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--public", type=Path, default=None, help="public data dir, used only to check query alignment")
    args = parser.parse_args()

    zf = zipfile.ZipFile(args.zip)
    all_entities = frozenset(range(NUM_ENTITIES))
    train = read_triples(zf, HPLUS + "train.txt")
    valid = read_triples(zf, HPLUS + "valid.txt")
    test = read_triples(zf, HPLUS + "test.txt")
    adj_obs = defaultdict(set)
    for h, r, t in train + valid:
        adj_obs[(h, r)].add(t)
    adj_obs = dict(adj_obs)
    full = array.array("i")
    for h, r, t in train + valid + test:
        full.extend((h, r, t))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "graph_full.npy").write_bytes(npy_bytes(full, (len(full) // 3, 3)))

    lookup = {v: k for k, v in STRUCTURES.items()}
    counts = {}
    for bench, bench_dir, types in [("std", STD, STD_TYPES), ("hplus", HPLUS, HPLUS_TYPES)]:
        queries = load_pickle(zf, bench_dir + "test-queries.pkl")
        easy = load_pickle(zf, bench_dir + "test-easy-answers.pkl")
        hard = load_pickle(zf, bench_dir + "test-hard-answers.pkl")
        names = {lookup[s]: s for s in queries if s in lookup}
        arrays = {}
        counts[bench] = {}
        for qtype in types:
            structure = names[qtype]
            chosen = sample_queries(queries[structure], bench, "test", qtype, CAP[bench])
            rows = array.array("i")
            hard_rows, filt_rows = [], []
            for q in chosen:
                rows.extend(query_row(structure, q))
                h = set(hard[q])
                f = set(easy.get(q, ())) | execute(structure, q, adj_obs, all_entities)
                if not h or h & f:
                    raise RuntimeError(f"bad hard answers for {bench}/{qtype}")
                hard_rows.append(h)
                filt_rows.append(f)
            width = len(rows) // len(chosen)
            arrays[f"q_{qtype}"] = (rows, (len(chosen), width))
            (a, sa), (b, sb) = csr(hard_rows)
            arrays[f"hard_{qtype}_indptr"], arrays[f"hard_{qtype}_indices"] = (a, sa), (b, sb)
            (a, sa), (b, sb) = csr(filt_rows)
            arrays[f"filt_{qtype}_indptr"], arrays[f"filt_{qtype}_indices"] = (a, sa), (b, sb)
            counts[bench][qtype] = len(chosen)
            if args.public is not None and (args.public / f"test_{bench}.npz").exists():
                if read_npz_q(args.public / f"test_{bench}.npz", f"q_{qtype}") != list(rows):
                    raise RuntimeError(f"public/hidden query mismatch for {bench}/{qtype}")
            print(f"  hidden {bench}/{qtype}: {len(chosen)} queries", flush=True)
        write_npz(args.out / f"test_{bench}_truth.npz", arrays)
        del queries, easy, hard

    meta = {
        "num_entities": NUM_ENTITIES,
        "types": {"std": STD_TYPES, "hplus": HPLUS_TYPES},
        "counts": counts,
        "prediction_list_length": 1000,
        "trace_list_length": 100,
    }
    (args.out / "meta.json").write_text(json.dumps(meta, indent=1) + "\n")
    digest = hashlib.sha256()
    for name in sorted(p.name for p in args.out.iterdir() if p.suffix in (".npz", ".npy", ".json")):
        digest.update(name.encode())
        digest.update((args.out / name).read_bytes())
    (args.out / ".complete").write_text(digest.hexdigest() + "\n")
    print("hidden test truth written to", args.out)


if __name__ == "__main__":
    main()
